#!/usr/bin/env python3
"""The PS1 build's objects, in link order, read from makefile.gaz (issue #98).

makefile.gaz stays the one list of what the PS1 build compiles: a game-source
change edits its <dir>_src (C++) and <dir>_src_mip (assembler) lists, as it
always has, and port/psx's CMake build reads them through this script at
configure time.  It resolves the lists as makefile.gaz did:

    SRC_DIRS      := $(patsubst source/%,%,$(wildcard source/*))
    ALL_ASM_OBJS  := every dir's <dir>_src_mip words, dirs in SRC_DIRS order
    ALL_CPP_OBJS  := every dir's <dir>_src words, the same way
    ALL_CODE_OBJS := $(ALL_ASM_OBJS) $(ALL_CPP_OBJS)

$(wildcard) gave the directories in the file system's order, which on NTFS
is case-insensitive (... projectl PsxBoot save ...); the $(...) references
inside the lists are expanded from makefile.gaz's own simple assignments
plus VERSION, TERRITORY and FILE_SYSTEM.

    psx_manifest.py --territory USA --version DEBUG [--out <file.cmake>]

writes PSX_ASM_SOURCES / PSX_CPP_SOURCES (<dir>/<file>, no extension) as
CMake lists, or prints them.
"""
import argparse
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
FILE_SYSTEM = "CD"

ASSIGN = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)[ \t]*:?=[ \t]*(.*?)[ \t]*$")
LIST = re.compile(r"^([a-z]+)_src(_mip)?$")


def logical_lines(path):
    """makefile lines with backslash continuations joined, comments dropped."""
    out, cur = [], ""
    with open(path, newline="") as f:
        for raw in f:
            line = raw.rstrip("\r\n")
            if line.rstrip().endswith("\\"):
                cur += line.rstrip()[:-1] + " "
                continue
            cur += line
            if not cur.lstrip().startswith("#"):
                out.append(cur)
            cur = ""
    return out


def expand(text, env):
    """$(VAR) and nested $($(VAR)_X), innermost first; an unknown name is an
    error (makefile.gaz would expand it to nothing, silently)."""
    pat = re.compile(r"\$\(([A-Za-z0-9_]+)\)")
    while True:
        m = pat.search(text)
        if not m:
            return text
        if m.group(1) not in env:
            raise SystemExit("psx_manifest: makefile.gaz list uses $(%s), which it does not assign"
                             % m.group(1))
        text = text[:m.start()] + env[m.group(1)] + text[m.end():]


def manifest(territory, version, root=ROOT):
    env = {"VERSION": version, "TERRITORY": territory, "FILE_SYSTEM": FILE_SYSTEM}
    lists = {}
    for line in logical_lines(os.path.join(root, "makefile.gaz")):
        m = ASSIGN.match(line)
        if not m:
            continue
        name, value = m.group(1), m.group(2)
        lst = LIST.match(name)
        if lst:
            lists[(lst.group(1), bool(lst.group(2)))] = value
        elif "$" not in value and name not in env:
            env[name] = value.strip()
    source = os.path.join(root, "source")
    dirs = sorted((d for d in os.listdir(source) if os.path.isdir(os.path.join(source, d))),
                  key=str.casefold)
    asm, cpp = [], []
    for d in dirs:
        for mip, out in ((True, asm), (False, cpp)):
            if (d, mip) in lists:
                out += ["%s/%s" % (d, w) for w in expand(lists[(d, mip)], env).split()]
    return asm, cpp


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--territory", required=True, choices=["USA", "EUR"])
    ap.add_argument("--version", required=True, choices=["DEBUG", "FINAL"])
    ap.add_argument("--out")
    a = ap.parse_args(argv)
    asm, cpp = manifest(a.territory, a.version)
    text = ("# generated by port/tools/psx/psx_manifest.py from makefile.gaz - do not edit\n"
            "set(PSX_ASM_SOURCES\n%s)\nset(PSX_CPP_SOURCES\n%s)\n"
            % ("".join("    %s\n" % s for s in asm), "".join("    %s\n" % s for s in cpp)))
    if a.out:
        old = open(a.out).read() if os.path.exists(a.out) else None
        if old != text:
            with open(a.out, "w", newline="\n") as f:
                f.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
