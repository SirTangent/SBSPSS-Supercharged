#!/usr/bin/env python3
"""Write the scripts' copy of the in-game string ids (issue #95).

A port of tools/Perl/pl/text_extract.pl.  scripter cannot read trans.h, so
the in-game ids go to data/Scripts/defs/trans.scr, which every script
#includes by that path:

- trans.h's enum runs from the line starting `{` to the one starting `}`.
  Each non-blank line between is one enum value, numbered from 0, named by
  its leading word.
- Each value whose name starts with the tag prefix is written as
  `#define <NAME>\\t\\t<number>`, after a comment header, CRLF.

Changes from text_extract.pl:
- The header names trans.h, not the path it was read from.  That path
  (out/USA/... or out/EUR/...) was all that told the two territories'
  trans.scr apart, and both write the one file.
- The file is written only when its content changes, and atomically, so a
  build of one territory doesn't make the other rebuild its scripts.
- A missing input, or one without the enum's braces, is an error;
  text_extract.pl's `open ... || die` never died.

    trans_scr.py <trans.h> <trans.scr> <tag prefix>
"""
import os
import re
import sys


class TransScrError(Exception):
    pass


def extract(header, prefix):
    """The (name, number) pairs of the enum values starting with `prefix`."""
    lines = iter(header.split(b"\n"))
    for line in lines:
        if line.startswith(b"{"):
            break
    else:
        raise TransScrError("no line starting { (the enum's start)")
    found = []
    number = 0
    for line in lines:
        if line.startswith(b"}"):
            return found
        if not line.strip(b" \t\r\n\f\v"):
            continue
        name = re.match(rb"[ \t\r\n\f\v]*(\w*)", line).group(1)
        if name.startswith(prefix):
            found.append((name, number))
        number += 1
    raise TransScrError("no line starting } (the enum's end)")


def trans_scr(header_name, header, prefix):
    out = [b"// TextIds for ingame text - Auto-generated by text_extract.pl",
           b"//",
           b"// Source file: " + header_name,
           b"// Tag prefix:  " + prefix,
           b""]
    out += [b"#define %s\t\t%d" % (name, number) for name, number in extract(header, prefix)]
    return b"".join(l + b"\r\n" for l in out)


def write_if_changed(path, data):
    try:
        with open(path, "rb") as f:
            if f.read() == data:
                return False
    except FileNotFoundError:
        pass
    tmp = "%s.%d.tmp" % (path, os.getpid())
    with open(tmp, "wb") as f:
        f.write(data)
    os.replace(tmp, path)
    return True


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2
    header_path, out_path, prefix = argv
    try:
        with open(header_path, "rb") as f:
            data = trans_scr(os.path.basename(header_path).encode("latin-1"), f.read(),
                             prefix.encode("latin-1"))
    except (TransScrError, OSError) as e:
        print("trans_scr.py: %s: %s" % (header_path, e), file=sys.stderr)
        return 1
    write_if_changed(out_path, data)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
