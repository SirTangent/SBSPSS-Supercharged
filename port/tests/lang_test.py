"""The data build's text steps, port/tools/data/lang.py and trans_scr.py, on
fixed cases (issue #95).

lang.py merges the translation files into transtext's final.dat and
trans_scr.py writes the scripts' copy of the in-game string ids; both
replace the 1999 Perl (tools/Perl/pl/lang.pl, text_extract.pl) and keep its
rules, which each case below pins.  Needs nothing but the two scripts.

    lang_test.py
"""
import os
import shutil
import sys
import tempfile

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools", "data"))
import lang  # noqa: E402
import trans_scr  # noqa: E402

failed = 0


def check(name, got, want):
    global failed
    ok = got == want
    failed += not ok
    print("%s  %s" % ("pass" if ok else "FAIL", name))
    if not ok:
        print("      got:  %r\n      want: %r" % (got, want))


def raises(name, fn):
    global failed
    try:
        fn()
    except (lang.LangError, trans_scr.TransScrError) as e:
        print("pass  %s (%s)" % (name, str(e).splitlines()[0]))
        return
    failed += 1
    print("FAIL  %s: no error" % name)


def lang_cases(tmp):
    def write(name, data):
        path = os.path.join(tmp, name).replace("\\", "/")
        open(path, "wb").write(data)
        return path

    # English: CRLF, comments, blank lines, another language's line inside a
    # block, a text with `=` before its real line, a repeated id, CP1252.
    eng = write("text.dat",
                b"; header comment\r\n\r\n"
                b"[STR__FIRST]\r\nger=ignored\r\neng=One ; a comment\r\n"
                b"[STR__SECOND]\r\n\r\n; only a comment\r\neng=a=b\r\neng=Two\r\n"
                b"[STR__THIRD]\r\neng=\x91caf\xe9\x92 %d\r\n"
                b"[STR__FIRST]\r\neng=One again ; the space before ; stays\r\n")
    # A language file: LF lines, an empty translation, an id English lacks.
    ger = write("ger.dat",
                b"[STR__FIRST]\neng=not german\nger=Eins\n"
                b"[STR__SECOND]\nger=\n"
                b"[STR__EXTRA]\nger=Nur deutsch\n")
    swe = write("swe.dat", b"[STR__THIRD]\r\nswe=Tre %d\r\n")
    check("final.dat: first-appearance order, last text, translations in argument order",
          lang.final_dat(lang.merge(eng, [ger, swe])),
          b"[STR__FIRST]\r\neng=One again \r\nger=Eins\r\n\r\n"
          b"[STR__SECOND]\r\neng=Two\r\n\r\n"
          b"[STR__THIRD]\r\neng=\x91caf\xe9\x92 %d\r\nswe=Tre %d\r\n\r\n")
    check("prefix from a \\ path", lang.language_prefix("C:\\x\\dut.dat", b""), b"dut")
    check("prefix from a / path", lang.language_prefix("data/translations/ita.dat", b""), b"ita")
    check("no separator keeps the previous prefix", lang.language_prefix("spa.dat", b"ita"), b"ita")

    # A final line without a newline loses its last character (lang.pl's chop).
    last = write("last.dat", b"[STR__A]\r\neng=abc")
    check("chop of an unterminated last line", lang.read_trans(last, b"eng"), {b"STR__A": b"ab"})

    bad_id = write("bad_id.dat", b"[STR__A B]\r\neng=x\r\n")
    raises("an id outside A-Z a-z 0-9 _", lambda: lang.read_trans(bad_id, b"eng"))
    no_eq = write("no_eq.dat", b"[STR__A]\r\nno equals\r\n")
    raises("a line with no =", lambda: lang.read_trans(no_eq, b"eng"))
    eof = write("eof.dat", b"[STR__A]\r\nger=nur\r\n")
    raises("end of file inside an id (lang.pl looped)", lambda: lang.read_trans(eof, b"eng"))

    out = os.path.join(tmp, "final.dat")
    check("main writes final.dat", lang.main([eng, out, ger, swe]), 0)
    check("main's file matches", open(out, "rb").read(), lang.final_dat(lang.merge(eng, [ger, swe])))


HEADER = (b"#ifndef __STRING_ENUMS__\r\n#define __STRING_ENUMS__\r\nenum\r\n{\r\n\r\n"
          b"\tSTR__INGAME__A,\r\n\tSTR__OTHER,\r\n\r\n\tSTR__INGAME__B,\r\n\tSTR__INGAME,\r\n"
          b"};\r\n#endif\r\n")


def trans_scr_cases(tmp):
    check("trans.scr: header, the prefixed ids numbered by enum position",
          trans_scr.trans_scr(b"trans.h", HEADER, b"STR__INGAME__"),
          b"// TextIds for ingame text - Auto-generated by text_extract.pl\r\n//\r\n"
          b"// Source file: trans.h\r\n// Tag prefix:  STR__INGAME__\r\n\r\n"
          b"#define STR__INGAME__A\t\t0\r\n#define STR__INGAME__B\t\t2\r\n")
    raises("no enum start", lambda: trans_scr.extract(b"enum\r\n", b"STR__"))
    raises("no enum end", lambda: trans_scr.extract(b"{\r\n\tSTR__A,\r\n", b"STR__"))
    path = os.path.join(tmp, "trans.scr")
    check("first write", trans_scr.write_if_changed(path, b"x"), True)
    check("same content is not rewritten", trans_scr.write_if_changed(path, b"x"), False)
    check("new content is", trans_scr.write_if_changed(path, b"y"), True)


def main():
    tmp = tempfile.mkdtemp(prefix="sbsp_lang_")
    try:
        lang_cases(tmp)
        trans_scr_cases(tmp)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print("%d failed" % failed if failed else "all passed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
